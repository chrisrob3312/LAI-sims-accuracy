#!/usr/bin/env bash
# ============================================================================
# fetch-almarri-vcfs.sh
#
# Download the Almarri et al. 2021 Middle East phased VCFs from the Sanger
# public share, and emit the sample/population crosswalk our pipeline needs.
#
# WHY VCFs AND NOT THE ENA CRAMs: ENA study ERP110713 holds lane-level raw
# alignments (e.g. 26958_8#2.cram, with multiple runs per sample), which would
# mean re-calling ~137 genomes -- terabytes of download and weeks of compute,
# to reproduce calls the authors already made. The Sanger share publishes the
# called, phased VCFs directly. Use those.
#
# WHAT THESE FILES ARE, per the share's own README:
#   "The Phased VCFs provided in this directory are the unfiltered SNV calls
#    generated by the longranger software."
# So: GRCh38, SNVs only (no indels), UNFILTERED, phased by Long Ranger from
# 10x linked reads, and ONE FILE PER SAMPLE.
#
# THE TRAP THAT FOLLOWS FROM "ONE FILE PER SAMPLE" -- read before merging.
# Almarri et al.'s own methods describe it:
#   "Because variants were called for each sample separately, homozygous ref
#    alleles were assigned as missing when joined with other samples, causing
#    an artificially high missingness rate. To resolve this, we used
#    `bcftools plugin missing2ref` to switch missing alleles to ref."
# A naive `bcftools merge` therefore produces a panel that looks almost
# entirely missing. The merge stage MUST fill absent genotypes as 0/0. This
# script only downloads; 1d_almarri_prep_clm.sh merges.
#
# The paper's QC was PASS + GQ > 20, then missing2ref -- which turns every
# dropped low-quality call into 0/0 (24-28% of each sample's ALT calls on
# chr22). 1d v4 sets those calls MISSING instead and fills only what is absent
# (merge -0); see its header.
#
# Usage:
#   scripts/fetch-almarri-vcfs.sh                 # default ~/almarri_vcfs
#   DEST=/path/to/dir scripts/fetch-almarri-vcfs.sh
#   DRY_RUN=1 scripts/fetch-almarri-vcfs.sh       # list what would download
# ============================================================================
set -euo pipefail

BASE="${BASE:-https://ngs.sanger.ac.uk/production/appg}"
DEST="${DEST:-${HOME}/almarri_vcfs}"
DRY_RUN="${DRY_RUN:-}"

# Downloaded content is untrusted: keep it in its own directory, never run
# anything from inside it, and pass paths as arguments.
mkdir -p "$DEST/vcfs" "$DEST/meta"

echo "[almarri] source: $BASE"
echo "[almarri] dest  : $DEST"

# --- 1. metadata ----------------------------------------------------------
META="$DEST/meta/appg.meta"
if [[ ! -s "$META" ]]; then
    echo "[almarri] fetching appg.meta"
    curl -sSLf -o "$META" "$BASE/appg.meta"
fi
curl -sSLf -o "$DEST/meta/README" "$BASE/README" 2>/dev/null || true

N_META=$(awk 'NR>1 && NF' "$META" | wc -l)
echo "[almarri] metadata: ${N_META} samples"
echo "[almarri] populations:"
awk 'NR>1 && NF {print $4}' "$META" | sort | uniq -c | sort -rn | sed 's/^/    /'

# --- 2. crosswalk ---------------------------------------------------------
# appg.meta columns: long_ID short_ID pop_ID population annotation
# The VCFs are named by short_ID (APPG…); the Almarri .fam distributed with
# the HGDP-1kGP-Almarri panel uses pop_ID (IRAQ1, JORDAN1, OMAN1, SAUDI1…).
# Both are needed, and nothing downstream should guess between them.
XWALK="$DEST/meta/almarri_crosswalk.tsv"
awk 'NR==1 {print "short_ID\tpop_ID\tpopulation\tannotation"; next}
     NF {print $2"\t"$3"\t"$4"\t"$5}' "$META" > "$XWALK"
echo "[almarri] crosswalk -> $XWALK"

# --- 3. resolve filenames from the listing --------------------------------
# Filenames are inconsistent -- some carry a run prefix (26958_APPG…), some do
# not (APPG7555863…), one carries a suffix (APPG7555871_3…). They cannot be
# constructed from the ID, so match the real listing against each short_ID.
LISTING="$DEST/meta/phased_vcf_listing.txt"
echo "[almarri] fetching PHASED_VCFs/ listing"
curl -sSLf "$BASE/PHASED_VCFs/" \
  | grep -oiE 'href="[^"]+\.vcf\.gz"' | sed 's/href="//;s/"//' | sort -u > "$LISTING"
echo "[almarri] listing: $(wc -l < "$LISTING") .vcf.gz files"

MANIFEST="$DEST/meta/download_manifest.tsv"
: > "$MANIFEST"
MISSING=0
while read -r sid; do
    [[ -n "$sid" ]] || continue
    # Anchor on the ID so APPG7555871 cannot match APPG75558710.
    hits=$(grep -E "(^|_)${sid}(_|\.)" "$LISTING" || true)
    n=$(printf '%s\n' "$hits" | awk 'NF' | wc -l)
    if [[ "$n" -eq 0 ]]; then
        echo "[almarri] WARNING: no file for ${sid}" >&2
        MISSING=$((MISSING+1)); continue
    fi
    if [[ "$n" -gt 1 ]]; then
        echo "[almarri] NOTE: ${n} files for ${sid}; taking all:" >&2
        printf '%s\n' "$hits" | sed 's/^/    /' >&2
    fi
    printf '%s\n' "$hits" | awk -v s="$sid" 'NF {print s"\t"$0}' >> "$MANIFEST"
done < <(awk 'NR>1 && NF {print $2}' "$META")

echo "[almarri] matched $(wc -l < "$MANIFEST") files for ${N_META} samples (${MISSING} unmatched)"
[[ "$MISSING" -gt 0 ]] && echo "[almarri] ^ investigate before merging: an unmatched sample is silently absent"

if [[ -n "$DRY_RUN" ]]; then
    echo "[almarri] DRY_RUN -- first 10 planned downloads:"
    head -10 "$MANIFEST" | sed 's/^/    /'
    exit 0
fi

# --- 4. download (resumable, skips complete files) ------------------------
echo "[almarri] downloading to $DEST/vcfs"
n=0; tot=$(wc -l < "$MANIFEST")
while IFS=$'\t' read -r sid fname; do
    n=$((n+1))
    out="$DEST/vcfs/$fname"
    if [[ -s "$out" ]] && bcftools view -h "$out" >/dev/null 2>&1; then
        echo "[almarri] [$n/$tot] have $fname"
        continue
    fi
    echo "[almarri] [$n/$tot] fetching $fname"
    # -C - resumes a partial transfer rather than restarting it.
    curl -sSLf -C - -o "$out" "$BASE/PHASED_VCFs/$fname" || {
        echo "[almarri] ERROR downloading $fname" >&2; rm -f "$out"; continue; }
    # A truncated file can still be large, so validate by reading the header.
    if ! bcftools view -h "$out" >/dev/null 2>&1; then
        echo "[almarri] ERROR: $fname downloaded but bcftools cannot read it -- removing" >&2
        rm -f "$out"
    fi
done < "$MANIFEST"

OK=$(ls -1 "$DEST/vcfs"/*.vcf.gz 2>/dev/null | wc -l)
echo
echo "[almarri] complete: ${OK}/${tot} VCFs in $DEST/vcfs"
echo "[almarri] total size: $(du -sh "$DEST/vcfs" | cut -f1)"
cat <<EOF

NEXT: these are PER-SAMPLE calls. Merging them without filling absent
genotypes produces a panel that looks almost entirely missing, because hom-ref
sites are absent from each single-sample file and become ./. on merge.
1d_almarri_prep_clm.sh does it:

  1. low-quality calls -> missing (FILTER not PASS, GQ <= 20) -- NOT dropped:
     a dropped call would be filled as 0/0 in step 3
  2. bcftools norm -c w -m -snps --fasta-ref <GRCh38>, +fixref
  3. bcftools merge -0 all samples      <-- absent = 0/0; missing stays missing
  4. site mask, then hand to 1c for joint re-phasing with the panel

Joint re-phasing in step 5 is required even though these are already phased:
Long Ranger phased each sample independently, and appending an independently
phased cohort to an independently phased panel creates cohort-specific switch
errors that RFMix reads as ancestry switches.
EOF
